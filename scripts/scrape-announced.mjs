// Scrapes Applicant Auction's announced-intended-applications table and writes
// data/announced.ts. That page is a compiled list, not a source: every row
// links to the trade-press piece the announcement actually came from, and it
// is that URL we cite. Run it again before Reveal Day; it prints a diff of
// what changed against the file already on disk.
//
//   node scripts/scrape-announced.mjs
//
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const URL_ = "https://www.applicantauction.com/announced-intended-applications";
const OUT = new URL("../data/announced.ts", import.meta.url).pathname;

const strip = (s) =>
  s
    .replace(/<[^>]+>/g, " ")
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCharCode(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCharCode(+d))
    .replace(/&amp;/g, "&")
    .replace(/&(quot|apos|rsquo|lsquo|ldquo|rdquo|nbsp|mdash|ndash);/g, (_, e) =>
      ({ quot: '"', apos: "'", rsquo: "’", lsquo: "‘", ldquo: "“", rdquo: "”", nbsp: " ", mdash: "—", ndash: "–" })[e]
    )
    .replace(/\s+/g, " ")
    .trim();

// "D3 Global + Solana Foundation" — the lead entity operates the application,
// the rest are the brands behind it. Splitting there keeps the applicant list
// from fragmenting into a dozen near-identical D3 rows.
function splitParties(raw) {
  const cleaned = raw
    .replace(/\s*\.[a-z0-9]+ withdrawn.*$/i, "")
    .replace(/\s+(New|Withdrawn)\s*$/g, "")
    .replace(/\s+(New|Withdrawn)\s*$/g, "")
    .trim();
  const parts = cleaned.split(" + ").map((p) => p.trim());
  return { lead: parts[0], partners: parts.slice(1) };
}

const res = await fetch(URL_, {
  headers: { "user-agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)" },
});
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const html = await res.text();

const updated =
  strip(html.match(/Last updated\s*<[^>]*>([^<]+)/i)?.[1] ?? "").trim() ||
  "unknown";

const table = html.match(/<table[\s\S]*?<\/table>/)?.[0];
if (!table) throw new Error("no table found — the page layout changed");

const rows = [...table.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)]
  .map((m) => m[1])
  .filter((r) => r.includes("<td"));

const records = rows.map((r) => {
  const tds = [...r.matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((m) => m[1]);
  const rawCompany = strip(tds[0]);
  const rawStrings = strip(tds[1]);
  const { lead, partners } = splitParties(rawCompany);
  // Cells mix strings with prose: ".abion (dot-brand)", ".ape (contention
  // with D3 Global)", ".sol, .solana and other gTLDs". Keep the dot-prefixed
  // tokens, drop the commentary; rows with no token at all keep it as a note.
  const strings = [...rawStrings.matchAll(/\.([a-z0-9-]+)/g)]
    .map((m) => m[1])
    .filter((s, i, a) => a.indexOf(s) === i);
  return {
    lead,
    partners,
    strings,
    note: strings.length ? null : rawStrings,
    withdrawn: /\bWithdrawn\b/.test(rawCompany),
    sourceUrl: tds[2].match(/href="([^"]+)"/)?.[1] ?? null,
    sourceTitle: strip(tds[2]),
    date: strip(tds[3]),
  };
});

const body = `// Generated by scripts/scrape-announced.mjs — do not hand-edit.
// Source: ${URL_}
// Applicant Auction last updated: ${updated}

export type Announced = {
  lead: string;
  partners: string[];
  strings: string[];
  note: string | null; // set when the row names no concrete string
  withdrawn: boolean;
  sourceUrl: string | null;
  sourceTitle: string;
  date: string;
};

export const announcedUpdated = ${JSON.stringify(updated)};

export const announced: Announced[] = ${JSON.stringify(records, null, 2)};
`;

if (existsSync(OUT)) {
  const prev = readFileSync(OUT, "utf8");
  const old = new Set([...prev.matchAll(/"strings":\s*\[([^\]]*)\]/g)].flatMap((m) =>
    [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1])
  ));
  const now = new Set(records.flatMap((r) => r.strings));
  const added = [...now].filter((s) => !old.has(s));
  const gone = [...old].filter((s) => !now.has(s));
  console.log(`rows ${records.length} | +${added.length} strings, -${gone.length}`);
  if (added.length) console.log("  added:", added.map((s) => "." + s).join(", "));
  if (gone.length) console.log("  gone: ", gone.map((s) => "." + s).join(", "));
} else {
  console.log(`rows ${records.length} | ${now_count(records)} strings (first run)`);
}
function now_count(rs) {
  return new Set(rs.flatMap((r) => r.strings)).size;
}

writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
